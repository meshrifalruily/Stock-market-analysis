TRANSLITERATION_MAP = {
    "a": "ا", "b": "ب", "c": "ك", "d": "د", "e": "ي", "f": "ف", "g": "ج",
    "h": "ه", "i": "ي", "j": "ج", "k": "ك", "l": "ل", "m": "م", "n": "ن",
    "o": "و", "p": "ب", "q": "ق", "r": "ر", "s": "س", "t": "ت", "u": "و",
    "v": "ف", "w": "و", "x": "كس", "y": "ي", "z": "ز",
}

LEGAL_WORDS = {
    "company", "co", "ltd", "limited", "group", "holding", "holdings", "corporation",
    "plc", "jsc", "saudi", "arabian", "national", "international",
}

def transliterate_to_arabic(text):
    words = re.findall(r"[A-Za-z0-9]+", str(text))
    useful_words = [word for word in words if word.lower() not in LEGAL_WORDS]
    if not useful_words:
        useful_words = words[:3]
    rendered = []
    for word in useful_words[:5]:
        rendered.append("".join(TRANSLITERATION_MAP.get(char.lower(), char) for char in word))
    return "شركة " + " ".join(rendered).strip()

def get_arabic_company_name(symbol, fallback_name=""):
    symbol = str(symbol).strip()
    if symbol in ARABIC_COMPANY_NAMES:
        return ARABIC_COMPANY_NAMES[symbol]
    if fallback_name and not re.search(r"[A-Za-z]", str(fallback_name)):
        return str(fallback_name)
    return transliterate_to_arabic(fallback_name or symbol)
